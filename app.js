function dispName(name) {
  const notes = [];
  let n = String(name || '').replace(/［([^］]*)］|＜([^＞]*)＞/g, (_, a, b) => { notes.push(a || b); return ' '; });
  let words = n.split(/[\s　]+/).filter(Boolean).filter((w, i, arr) => w !== arr[i - 1]);
  const base = words[0];
  // 「根」「果実」などの部位、「通年平均」などの説明、最後の「生」は表示しない（ゆで・焼きなどは残す）
  words = words.filter((w, i) => i === 0 || !((DISP_DROP.has(w) && !(w === '根' && base === 'すぐきな')) || (w === '葉' && !DISP_KEEP_LEAF.has(base))));
  if (words.length > 1 && words[words.length - 1] === '生') words.pop();
  if (DISP_COMMON[words[0]]) { notes.unshift(words[0]); words[0] = DISP_COMMON[words[0]]; }
  n = words.join(' ');
  for (const [a, b] of DISP_PHRASE) if (n.startsWith(a)) n = b + n.slice(a.length);
  return { name: n || String(name || ''), note: notes.join('・') };
}


/* ---------- 必要量の計算 ---------- */
function bracketIndex(age) {
  return DRI.brackets.findIndex(([lo, hi]) => age >= lo && age <= hi);
}
function computeTargets(p) {
  if (!p || !p.age) return null;
  const age = Number(p.age);
  if (!(age >= 1)) return { unsupported: true };
  const i = bracketIndex(Math.floor(age));
  if (i < 0) return { unsupported: true };
  const sex = p.sex === 'f' ? 'f' : 'm';
  const add = sex === 'f' && ADD[p.status] ? ADD[p.status] : ADD.none;
  const rdaBase = DRI[sex].rda[i];
  const earBase = DRI[sex].ear[i];
  const w = Number(p.weight) || 0;
  const t = {
    bracket: DRI.brackets[i][2],
    sexLabel: sex === 'f' ? '女性' : '男性',
    rda: rdaBase + add.rda,
    ear: earBase + add.ear,
    addLabel: add.label,
    addRda: add.rda,
    goalPct: DRI.goal[i],
    weight: w || null,
    weightRef: null,
    frail: null,
    age,
  };
  if (age >= 18 && w > 0) {
    // 切上げ（食事摂取基準の丸め方に合わせる）
    t.weightRef = Math.ceil(w * ADULT_EAR_PER_KG * RDA_FACTOR) + add.rda;
  }
  // 高齢者の目安（1.2g/kg）。身長があれば標準体重（BMI22）を出し、
  // 太り気味（BMI25以上）や体重未入力のときは標準体重で計算する（多く出すぎないように）
  const h = Number(p.height) || 0;
  if (h > 0) {
    const hm = h / 100;
    t.stdWeight = Math.round(22 * hm * hm * 10) / 10;
    if (w > 0) t.bmi = Math.round(w / (hm * hm) * 10) / 10;
  }
  if (age >= 65) {
    let base = w, useStd = false;
    if (t.stdWeight && (!w || t.bmi >= 25)) { base = t.stdWeight; useStd = true; }
    if (base > 0) { t.frail = Math.ceil(base * FRAIL_PER_KG); t.frailBase = base; t.frailStd = useStd; }
  }
  // カロリーの目安（推定エネルギー必要量）。表に値がない活動量は「ふつう」で
  const act = ['low', 'mid', 'high'].includes(p.activity) ? p.activity : 'mid';
  const eerV = EER[sex][act][i] ?? EER[sex].mid[i];
  t.eer = eerV + (sex === 'f' ? EER.add[p.status] || 0 : 0);
  t.eerAct = EER[sex][act][i] != null ? act : 'mid';
  t.bmiGoal = bmiGoal(age);
  // 体重からの参考値も、太り気味なら標準体重で
  if (t.weightRef && t.stdWeight && t.bmi >= 25) { t.weightRef = Math.ceil(t.stdWeight * ADULT_EAR_PER_KG * RDA_FACTOR) + add.rda; t.weightRefStd = true; }
  return t;
}

