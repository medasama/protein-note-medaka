function splitName(name) {
  // 先頭の ＜…＞ や （…） を分類として分ける
  let rest = name.trim();
  const sub = [];
  let m;
  while ((m = rest.match(/^[＜（]([^＞）]+)[＞）]\s*/))) {
    sub.push(m[1]);
    rest = rest.slice(m[0].length);
  }
  return { main: rest, sub: sub.join('・'), parts: sub };
}

