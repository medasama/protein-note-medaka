  if (!d0) return '';
  const d = d0.gu ? Object.assign({}, d0, { items: guDishItem(d0, sel).guItems }) : d0;
  if (d.fixed != null) return `${DISH_SRC[d.src] || ''}（${d.unit}・${d.ml ? '内容量' + d.ml + 'mL' : '可食部' + d.g + 'g'}${d.srcNote ? '。' + d.srcNote : ''}）。店舗・時期により変わることがあります。`;
